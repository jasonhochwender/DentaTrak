 'needs_review_only','page_of','progress_sent','sending_bg','send_paused_note','confirm_stop_send'];

foreach ($T as $loc => $tr) {
    $f = __DIR__ . '/locales/' . $loc . '.json';
    $s = file_get_contents($f);
    if ($s === false) { echo "$loc: READ FAIL\n"; continue; }
    // Insert new keys after the "threads_none" line inside marketing_admin.
    if (strpos($s, '"pause_sending"') !== false) { echo "$loc: already patched\n"; continue; }
    $block = '';
    foreach ($order as $k) {
        $v = json_encode($tr[$k], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
        $block .= '        "' . $k . '": ' . $v . ",\n";
    }
    // threads_none is the anchor; it may or may not be last before our block.
    if (!preg_match('/^(\s*)"threads_none":.*$/m', $s, $m)) { echo "$loc: anchor missing\n"; continue; }
    $indent = $m[1];
    $block = '';
    foreach ($order as $k) {
        $v = json_encode($tr[$k], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
        $block .= $indent . '"' . $k . '": ' . $v . ",\n";
    }
    // Insert after the threads_none line; strip trailing comma issue by
    // ensuring threads_none line keeps its comma (it already ends with , or not).
    $s = preg_replace('/^(\s*)"threads_none":([^\n]*\n)/m', '$0' . $block, $s, 1);
    // max_recipients_label -> 500
    $s = preg_replace('/"max_recipients_label":\s*"[^"]*"/', '"max_recipients_label": "500"', $s, 1);
    // over_recipient_limit -> generic text
    $ov = json_encode($tr['over_limit'], JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES);
    $s = preg_replace('/"over_recipient_limit":\s*"[^"]*"/', '"over_recipient_limit": ' . $ov, $s, 1);
    file_put_contents($f, $s);
    echo "$loc: patched\n";
}
echo "done\n";
