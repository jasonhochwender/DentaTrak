      <h4>5. Data Sharing</h4>
      <p>We do not sell your information. Sharing within the Service is primarily controlled by the Practice that owns or manages the data:</p>
      <ul>
        <li>Practice administrators may invite users and External Collaborators to access the Service or specific Practice or case information</li>
        <li>Practice and case information may be accessible to authorized users and External Collaborators based on the roles, permissions, and access levels the Practice has assigned</li>
        <li>The Practice controls invitations and is responsible for authorization decisions; we provide the mechanism, but the Practice decides who is invited and what they may access</li>
        <li>Practice administrators may view membership, role, invitation, access, and related activity information for their Practice to manage accounts and access</li>
        <li>An External Collaborator invited by multiple Practices accesses each Practice's information under the permissions independently granted by each Practice; permissions granted by one Practice do not extend to another Practice's information unless separately authorized</li>
        <li>Being invited to access one Practice's information is not permission to use or disclose that information for unrelated purposes</li>
        <li>We share information with service providers who help us operate the Service (under appropriate agreements)</li>
        <li>We may share information when required by law or to protect our rights</li>
        <li>We may share information with your consent</li>
      </ul>

