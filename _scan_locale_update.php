foreach ($locales as $loc) {
    $file = $base . $loc . '.json';
    $data = json_decode(file_get_contents($file), true);
    if (!is_array($data)) { echo "$loc: JSON parse failed\n"; continue; }
    if (!isset($data['scanner']) || !is_array($data['scanner'])) $data['scanner'] = [];
    $data['scanner'] = array_merge($data['scanner'], $strings[$loc]);
    $json = json_encode($data, JSON_UNESCAPED_UNICODE | JSON_UNESCAPED_SLASHES | JSON_PRETTY_PRINT);
    if (file_put_contents($file, $json) === false) { echo "$loc: write failed\n"; continue; }
    echo "$loc: ok\n";
}
